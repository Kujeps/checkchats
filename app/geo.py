COUNTRY_RE = {c: re.compile("|".join(p), re.I) for c, p in COUNTRY_WORDS.items()}
RU_PHONE_RE = re.compile(r"(?:\+7|(?<!\d)8)[\s\-(]*9\d\d")   # мобильные России: +7 9xx / 8 9xx
UA_LETTERS_RE = re.compile(r"[їєґ]", re.I)
BY_LETTERS_RE = re.compile(r"ў", re.I)
KZ_LETTERS_RE = re.compile(r"[әғқңөұүһ]", re.I)


def guess(texts: list, title: str = "", about: str = "") -> dict:
    """{"country": "RU"|...|"?", "city": str|None, "scores": {...}}."""
    # Название и описание весят больше: там обычно прямо написан город или страна
    weighted = [(title or "", 3), (about or "", 3)] + [(t or "", 1) for t in texts]
    scores = Counter()
    cities = Counter()
    for text, w in weighted:
        low = text.lower()
        if not low.strip():
            continue
        for c, rx in COUNTRY_RE.items():
            n = len(rx.findall(low))
            if n:
                scores[c] += min(n, 3) * w
        if RU_PHONE_RE.search(low):
            scores["RU"] += 2 * w
        if UA_LETTERS_RE.search(low):
            scores["UA"] += 2 * w
        if BY_LETTERS_RE.search(low):
            scores["BY"] += 2 * w
        if len(KZ_LETTERS_RE.findall(low)) >= 3:
            scores["KZ"] += 2 * w
        for rx, city in _CITY_PATTERNS:
            n = len(rx.findall(low))
            if n:
                scores["RU"] += min(n, 3) * w
                if city:
                    cities[city] += n * w

    country = "?"
    if scores:
        (top, best), *rest = scores.most_common(2) + [(None, 0)]
        second = rest[0][1] if rest else 0
        # нужен заметный перевес и хотя бы пара признаков
        if best >= 2 and best >= 1.5 * second:
            country = top
    city = cities.most_common(1)[0][0] if country == "RU" and cities else None
    return {"country": country, "city": city, "scores": dict(scores)}


def combine(heur: dict, ai: dict) -> tuple:
    """Итоговые страна и город: ИИ видит контекст лучше, но без его ответа берём эвристику."""
    country = (ai or {}).get("country") or "?"
    if country == "?":
        country = (heur or {}).get("country") or "?"
    city = (ai or {}).get("city") or ((heur or {}).get("city") if country == "RU" else None)
    return country, city


def backfill(db) -> int:
    """Чаты, проверенные до появления гео: оцениваем страну по названию и описанию (бесплатно, без Telegram)."""
    rows = db.all_("SELECT id, title, about FROM chats WHERE status='checked' AND country IS NULL")
    for r in rows:
        g = guess([], r["title"] or "", r["about"] or "")
        db.q("UPDATE chats SET country=?, city=? WHERE id=?", (g["country"], g["city"], r["id"]))
    return len(rows)
